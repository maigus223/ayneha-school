/**
 * Contenu de lecture : de vrais mots songhay, validés par l'auteur de l'AYNEHA (13 oct. 2026).
 *
 * RÈGLE : un mot ou un texte n'apparaît dans la version publiée que si valide = true. Dans la
 * version de test (debug), tout s'affiche, avec un badge « à valider » sur ce qui ne l'est pas.
 *
 * [ayneha] : l'écriture exacte de l'auteur, mot par mot, dans l'ordre de lecture (nouvelle plage
 * U+10FF7C - U+10FFDD). S'il est absent, l'écriture vient du transcripteur.
 */
data class MotLecture(
    val latin: String,
    val francais: String,
    val valide: Boolean = false,
    val ayneha: List<List<Int>>? = null,
    /** Thème du lexique (« La famille », « Les animaux »...), vide pour les autres listes. */
    val theme: String = "",
) {
    /** Les mots AYNEHA (ordre de lecture). */
    val mots: List<List<Int>>
        get() = ayneha ?: Transcripteur.transcrire(latin).flatten().map { it.points }

    /** Tous les points de code, mots mis bout à bout. */
    val points: List<Int> get() = mots.flatten()

    /** Un seul mot, uniquement des glyphes AYNEHA (utilisable dans l'exercice de composition). */
    val composable: Boolean get() = mots.size == 1 && points.all { Ayneha.estAyneha(it) }
}

/** Une ligne de texte : le latin et l'écriture AYNEHA (mots, ordre de lecture). */
data class LigneTexte(val latin: String, val mots: List<List<Int>>)

data class TexteLecture(
    val titre: String,
    val lignes: List<LigneTexte>,
    val valide: Boolean = false,
    val note: String? = null,
)

