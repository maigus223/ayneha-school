    /** Ce qui peut être montré : tout en version de test, seulement le validé en version publiée. */
    fun visibles(liste: List<MotLecture>, test: Boolean): List<MotLecture> =
        if (test) liste else liste.filter { it.valide }

    fun textesVisibles(test: Boolean): List<TexteLecture> =
        if (test) TEXTES else TEXTES.filter { it.valide }

    /** Exemples pour la fiche d'une lettre : mots qui contiennent l'une de ses formes. */
    fun exemples(lettre: Lettre, test: Boolean, max: Int = 3): List<MotLecture> {
        val formes = lettre.variantes.values.toSet()
        return visibles(TOUS_LES_MOTS + NOMS, test)
            .filter { m -> m.points.any { it in formes } }
            .sortedBy { m -> m.points.size }
            .take(max)
    }
